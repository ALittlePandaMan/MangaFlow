import {describe, expect, it, vi} from 'vitest'
import {TaskActivity} from './taskActivity'
import {taskFixture} from './taskActivity.testUtils'

describe('current-operation task snapshots', () => {
  it.each(['QUEUED','RUNNING','CANCELLING','PAUSED'])('locks only the owning page for a %s task', status=>{
    const activity=new TaskActivity('project')
    activity.begin([taskFixture('1',{status})])
    expect(activity.hasPendingTasks()).toBe(true)
    expect(activity.getPageTask('page-1')?.id).toBe('1')
    expect(activity.getPageTask('unrelated-page')).toBeNull()
    activity.update([taskFixture('1',{status:'COMPLETED'})])
    expect(activity.getPageTask('page-1')).toBeNull()
    expect(activity.hasPendingTasks()).toBe(false)
  })
  it('keeps every current live task available for scrolling and page locks', () => {
    const activity=new TaskActivity('project')
    const tasks=Array.from({length:8},(_,i)=>taskFixture(`${i}`))
    tasks[0]={...tasks[0],status:'RUNNING'}
    activity.update([...tasks,taskFixture('99',{status:'COMPLETED'})])
    expect(activity.getSnapshot().tasks.map(task=>task.id)).toEqual(['0','7','6','5','4','3','2','1'])
    expect(activity.getSnapshot().active).toBe(8)
    expect(activity.getPageTask('page-1')?.id).toBe('1')
    expect(activity.getSnapshot().total).toBe(8)
  })
  it('never turns old completed, failed or cancelled history into current activity', () => {
    const activity=new TaskActivity('project')
    const before=activity.getSnapshot()
    activity.update(['COMPLETED','FAILED','CANCELLED'].map((status,i)=>taskFixture(`${i}`,{status})))
    expect(activity.getSnapshot()).toBe(before)
    expect(activity.getSnapshot().completion).toBeNull()
  })
  it('keeps unchanged snapshots stable and rejects stale responses and other projects', () => {
    const activity=new TaskActivity('project'),listener=vi.fn()
    activity.subscribe(listener)
    const running=taskFixture('1',{status:'RUNNING',progress:.5})
    activity.update([running])
    const snapshot=activity.getSnapshot()
    activity.update([{...running},taskFixture('2',{project_id:'other'})])
    expect(activity.getSnapshot()).toBe(snapshot)
    expect(listener).toHaveBeenCalledTimes(1)
    activity.update([{...running,progress:.1,updated_at:'2026-10-18T00:59:00Z'}])
    expect(activity.getSnapshot()).toBe(snapshot)
    activity.update([{...running,status:'COMPLETED',progress:1}])
    activity.update([running])
    expect(activity.getSnapshot().active).toBe(0)
    expect(activity.getPageTask('page-1')).toBeNull()
  })
  it('registers an explicitly submitted operation even when it completes immediately', () => {
    const activity=new TaskActivity('project')
    activity.record(taskFixture('1',{status:'COMPLETED',progress:1}))
    expect(activity.getSnapshot().completion).toMatchObject({total:1,completed:1,failed:0,cancelled:0})
    expect(activity.getSnapshot().tasks).toHaveLength(0)
  })
  it('appends continuous submissions without hiding older running or queued work', () => {
    const activity=new TaskActivity('project')
    activity.record(taskFixture('1',{status:'RUNNING'}))
    activity.record(taskFixture('2'))
    activity.record(taskFixture('3',{status:'COMPLETED',progress:1}))
    expect(activity.getSnapshot().tasks.map(task=>task.id)).toEqual(['1','2'])
    expect(activity.getSnapshot()).toMatchObject({active:2,total:3,completion:null})
    activity.update([taskFixture('1',{status:'CANCELLED'}),taskFixture('2',{status:'COMPLETED',progress:1})])
    expect(activity.getSnapshot().completion).toMatchObject({total:3,completed:2,cancelled:1})
  })
  it('replaces old activity without dropping locks for unrelated ongoing work', () => {
    const activity=new TaskActivity('project')
    activity.begin([taskFixture('1',{status:'RUNNING'})])
    activity.begin([taskFixture('2')])
    expect(activity.getSnapshot().tasks.map(task=>task.id)).toEqual(['2'])
    expect(activity.getSnapshot().active).toBe(2)
    expect(activity.getPageTask('page-1')?.id).toBe('1')
  })
  it('dismisses completion once and ignores late old results and old dismiss timers', () => {
    const activity=new TaskActivity('project')
    const first=taskFixture('1',{status:'COMPLETED',progress:1})
    activity.begin([first])
    const id=activity.getSnapshot().completion!.id
    activity.dismissCompletion(id)
    activity.update([{...first}])
    expect(activity.getSnapshot().completion).toBeNull()
    activity.begin([taskFixture('2',{status:'COMPLETED',progress:1})])
    activity.update([taskFixture('1',{status:'RUNNING'})])
    activity.dismissCompletion(id)
    expect(activity.getSnapshot().completion).toMatchObject({total:1,completed:1})
    expect(activity.getSnapshot().active).toBe(0)
  })
  it('summarizes all 336 submitted tasks instead of retaining completed history rows', () => {
    const activity=new TaskActivity('project')
    activity.begin(Array.from({length:336},(_,i)=>taskFixture(`${i}`)))
    expect(activity.getSnapshot().active).toBe(336)
    activity.update(Array.from({length:336},(_,i)=>taskFixture(`${i}`,{status:'COMPLETED',progress:1})))
    expect(activity.getSnapshot().tasks).toHaveLength(0)
    expect(activity.getSnapshot().completion).toMatchObject({total:336,completed:336})
    expect(activity.getSnapshot().total).toBe(336)
  })
  it('waits for all recovery chunks before reporting that an operation is complete', () => {
    const activity=new TaskActivity('project')
    activity.setRecovering(true)
    activity.update([taskFixture('1')])
    activity.update([taskFixture('1',{status:'COMPLETED',progress:1})])
    expect(activity.getSnapshot().completion).toBeNull()
    activity.update([taskFixture('2'),taskFixture('old',{status:'FAILED'})])
    activity.update([taskFixture('2',{status:'COMPLETED',progress:1})])
    activity.setRecovering(false)
    expect(activity.getSnapshot().completion).toMatchObject({total:2,completed:2})
  })
  it('does not report success for failure, cancellation or paused work', () => {
    const activity=new TaskActivity('project')
    activity.begin([taskFixture('1',{status:'COMPLETED'}),taskFixture('2',{status:'FAILED'}),
      taskFixture('3',{status:'CANCELLED'}),taskFixture('4',{status:'PAUSED'})])
    expect(activity.getSnapshot().completion).toBeNull()
    activity.update([taskFixture('4',{status:'CANCELLED'})])
    expect(activity.getSnapshot().completion).toMatchObject({total:4,completed:1,failed:1,cancelled:2})
  })
  it('starts a real restarted task but never reopens a stale terminal task', () => {
    const activity=new TaskActivity('project')
    activity.begin([taskFixture('1',{status:'COMPLETED'})])
    activity.begin([taskFixture('2',{status:'COMPLETED'})])
    activity.update([taskFixture('1',{status:'RUNNING',updated_at:'2026-10-18T02:00:00Z'})])
    expect(activity.getSnapshot().tasks.map(task=>task.id)).toEqual(['1'])
    expect(activity.getSnapshot().completion).toBeNull()
  })
})
